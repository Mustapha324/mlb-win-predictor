alter table public.prediction_snapshots enable row level security;
alter table public.saved_predictions enable row level security;
alter table public.model_refresh_runs enable row level security;

create policy "profiles_select_own" on public.profiles for select using (auth.uid() = id);
create policy "favorite_teams_own" on public.favorite_teams for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "prediction_snapshots_public_read" on public.prediction_snapshots for select using (true);
create policy "saved_predictions_own" on public.saved_predictions for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

revoke update on public.profiles from authenticated;
grant update (display_name) on public.profiles to authenticated;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create or replace function public.redeem_pro_code(p_code text)
returns jsonb
language plpgsql
security definer set search_path = public
as $$
declare
  v_code public.promo_codes%rowtype;
  v_user uuid := auth.uid();
  v_hash text;
begin
  if v_user is null then
    return jsonb_build_object('ok', false, 'message', 'Sign in before redeeming a code.');
  end if;
  v_hash := encode(digest(upper(trim(p_code)), 'sha256'), 'hex');
  select * into v_code from public.promo_codes where code_hash = v_hash for update;
  if v_code.id is null then
    return jsonb_build_object('ok', false, 'message', 'That invite code is invalid.');
  end if;
  if v_code.redeemed_by is not null then
    return jsonb_build_object('ok', false, 'message', 'That invite code has already been used.');
  end if;

  update public.promo_codes
    set redeemed_by = v_user, redeemed_at = now()
    where id = v_code.id and redeemed_by is null;
  if not found then
    return jsonb_build_object('ok', false, 'message', 'That invite code has already been used.');
  end if;

  update public.profiles
    set access_tier = 'friends_family', pro_source = 'friends_family', pro_expires_at = null, updated_at = now()
    where id = v_user;
  return jsonb_build_object('ok', true, 'message', 'Permanent Friends & Family Pro is active.');
end;
$$;

revoke all on function public.redeem_pro_code(text) from public;
grant execute on function public.redeem_pro_code(text) to authenticated;

