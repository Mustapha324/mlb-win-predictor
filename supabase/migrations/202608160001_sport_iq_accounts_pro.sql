create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text,
  access_tier text not null default 'free' check (access_tier in ('free', 'pro', 'friends_family')),
  pro_source text check (pro_source is null or pro_source in ('stripe', 'friends_family', 'admin')),
  pro_expires_at timestamptz,
  stripe_customer_id text unique,
  stripe_subscription_id text unique,
  subscription_status text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.promo_codes (
  id uuid primary key default gen_random_uuid(),
  code_hash text not null unique,
  label text not null default 'Friends & Family',
  redeemed_by uuid unique references public.profiles(id),
  redeemed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.favorite_teams (
  user_id uuid not null references public.profiles(id) on delete cascade,
  sport text not null check (sport in ('mlb', 'nfl')),
  team_id text not null,
  team_name text not null,
  created_at timestamptz not null default now(),
  primary key (user_id, sport, team_id)
);

create table if not exists public.prediction_snapshots (
  id uuid primary key default gen_random_uuid(),
  sport text not null check (sport in ('mlb', 'nfl')),
  game_id text not null,
  scheduled_at timestamptz not null,
  away_team text not null,
  home_team text not null,
  pregame_predicted_winner text not null,
  pregame_home_win_probability double precision not null check (pregame_home_win_probability between 0 and 1),
  pregame_away_win_probability double precision not null check (pregame_away_win_probability between 0 and 1),
  model_version text not null,
  factors jsonb not null default '[]'::jsonb,
  locked_at timestamptz not null default now(),
  actual_winner text,
  away_score integer,
  home_score integer,
  final_at timestamptz,
  unique (sport, game_id)
);

create table if not exists public.saved_predictions (
  user_id uuid not null references public.profiles(id) on delete cascade,
  prediction_id uuid not null references public.prediction_snapshots(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, prediction_id)
);

create table if not exists public.model_refresh_runs (
  id bigint generated by default as identity primary key,
  sport text not null check (sport in ('mlb', 'nfl')),
  ran_at timestamptz not null default now(),
  status text not null check (status in ('success', 'failed')),
  games_refreshed integer not null default 0,
  player_picks_refreshed integer not null default 0,
  error_message text
);

